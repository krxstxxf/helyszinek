-- FiveM Locator / Supabase setup
-- 1) Futtasd ezt a teljes SQL-t a Supabase Dashboard > SQL Editor menüben.
-- 2) A Supabase Authentication > Users alatt hozz létre egy felhasználót e-mail + erős jelszóval.
-- 3) Másold ki a felhasználó UUID-ját, majd futtasd a lenti admin-hozzárendelő INSERT-et.
-- 4) A Storage-ban hozz létre egy PUBLIC bucketet "place-images" néven (vagy futtasd az alábbi bucket sort).

create table if not exists public.places (
  id bigint generated by default as identity primary key,
  category text not null check (category in ('Dealer','Ammónia')),
  region text not null,
  code text not null default '',
  description text not null,
  image_url text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.admin_users (
  user_id uuid primary key references auth.users(id) on delete cascade,
  created_at timestamptz not null default now()
);

alter table public.places enable row level security;
alter table public.admin_users enable row level security;

create or replace function public.is_admin()
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (
    select 1 from public.admin_users
    where user_id = (select auth.uid())
  );
$$;

revoke all on function public.is_admin() from public;
grant execute on function public.is_admin() to anon, authenticated;

drop policy if exists "Anyone can read places" on public.places;
create policy "Anyone can read places" on public.places
for select to anon, authenticated using (true);

drop policy if exists "Admins can insert places" on public.places;
create policy "Admins can insert places" on public.places
for insert to authenticated with check ((select public.is_admin()));

drop policy if exists "Admins can update places" on public.places;
create policy "Admins can update places" on public.places
for update to authenticated using ((select public.is_admin())) with check ((select public.is_admin()));

drop policy if exists "Admins can delete places" on public.places;
create policy "Admins can delete places" on public.places
for delete to authenticated using ((select public.is_admin()));

drop policy if exists "Admins can read their admin row" on public.admin_users;
create policy "Admins can read their admin row" on public.admin_users
for select to authenticated using (user_id = (select auth.uid()));

grant select on public.places to anon, authenticated;
grant insert, update, delete on public.places to authenticated;
grant usage, select on sequence public.places_id_seq to authenticated;

-- Public image bucket. Upload/change/delete are admin-only; images are publicly viewable.
insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values ('place-images', 'place-images', true, 5242880, array['image/jpeg','image/png','image/webp'])
on conflict (id) do update set public = true, file_size_limit = 5242880, allowed_mime_types = array['image/jpeg','image/png','image/webp'];

drop policy if exists "Public can view place images" on storage.objects;
create policy "Public can view place images" on storage.objects
for select to anon, authenticated using (bucket_id = 'place-images');

drop policy if exists "Admins upload place images" on storage.objects;
create policy "Admins upload place images" on storage.objects
for insert to authenticated with check (bucket_id = 'place-images' and (select public.is_admin()));

drop policy if exists "Admins update place images" on storage.objects;
create policy "Admins update place images" on storage.objects
for update to authenticated using (bucket_id = 'place-images' and (select public.is_admin())) with check (bucket_id = 'place-images' and (select public.is_admin()));

drop policy if exists "Admins delete place images" on storage.objects;
create policy "Admins delete place images" on storage.objects
for delete to authenticated using (bucket_id = 'place-images' and (select public.is_admin()));

